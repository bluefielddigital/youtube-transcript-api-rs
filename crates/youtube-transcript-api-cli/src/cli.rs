//! The command line: argument parsing, running against a client, and writing
//! the output. Private to this binary, so any release may change it.

use std::io::{self, Write};
use std::time::Duration;

use clap::Parser;
use clap::builder::{PossibleValue, PossibleValuesParser, TypedValueParser};

use youtube_transcript_api::formatters::FormatterKind;
use youtube_transcript_api::proxies::{GenericProxyConfig, WebshareProxyConfig};
use youtube_transcript_api::{
    Error, FetchedTranscript, RawFormat, Transcript, TranscriptList, YouTubeTranscriptApi,
};

#[cfg(test)]
mod fake;
#[cfg(test)]

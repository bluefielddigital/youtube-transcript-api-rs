#[cfg(test)]
mod tests;

#[derive(Debug, Clone, PartialEq, Eq, Parser)]
#[command(
    name = "youtube-transcript-api",
    version,
    about = "Get the transcripts/subtitles for YouTube videos, including automatically \
             generated ones, without a headless browser."
)]
/// Command-line arguments.
pub struct Args {
    /// List of YouTube video IDs.
    #[arg(required = true)]
    pub video_ids: Vec<String>,

    /// List the languages the given videos are available in.
    #[arg(long)]
    pub list_transcripts: bool,

    /// Language codes in descending priority, for example `de en`: try German first,
    /// then English.
    #[arg(long, num_args = 0.., default_value = "en")]
    pub languages: Vec<String>,

    /// Which transcripts may match --languages.
    #[command(flatten)]
    pub matching: Matching,

    /// Output format.
    #[arg(long, value_parser = format_parser(), default_value_t)]
    pub format: FormatterKind,

    /// Translate the transcript to this language code. Use --list-transcripts
    /// to see which languages are available.
    #[arg(long)]
    pub translate: Option<String>,

    /// Your Webshare "Proxy Username" from <https://dashboard.webshare.io/proxy/settings>.
    #[arg(long, requires = "webshare_proxy_password")]
    pub webshare_proxy_username: Option<String>,

    /// Your Webshare "Proxy Password" from <https://dashboard.webshare.io/proxy/settings>.
    #[arg(long, requires = "webshare_proxy_username")]
    pub webshare_proxy_password: Option<String>,

    /// Use this HTTP proxy.
    #[arg(long, value_name = "URL")]
    pub http_proxy: Option<String>,

    /// Use this HTTPS proxy.
    #[arg(long, value_name = "URL")]
    pub https_proxy: Option<String>,

    /// Keep HTML formatting tags (italics, bold and the like) in the text.
    #[arg(long)]
    pub preserve_formatting: bool,

    /// Print the transcript in one of YouTube's own formats instead of
    /// --format.
    #[arg(long, value_parser = raw_parser(), value_name = "FORMAT", conflicts_with = "format")]
    pub raw: Option<RawFormat>,

    /// Give up on a request after this many seconds.
    #[arg(long, value_name = "SECONDS", value_parser = parse_timeout)]
    pub timeout: Option<Duration>,
}

/// Which transcripts may match `--languages`.
#[derive(Debug, Clone, PartialEq, Eq, clap::Args)]
pub struct Matching {
    /// Don't retrieve transcripts generated by YouTube.
    #[arg(long)]
    pub exclude_generated: bool,

    /// Don't retrieve manually created transcripts.
    #[arg(long)]
    pub exclude_manually_created: bool,

    /// Also match regional variants of --languages: `en` finds `en-US`, and
    /// `en-GB` finds `en`, when there is no exact match.
    #[arg(long)]
    pub match_language_variants: bool,
}

/// `--format`: the formatter names, each with its help.
fn format_parser() -> impl TypedValueParser<Value = FormatterKind> {
    PossibleValuesParser::new(
        FormatterKind::ALL
            .iter()
            .map(|&kind| PossibleValue::new(kind.name()).help(format_help(kind))),
    )
    .try_map(|name| name.parse::<FormatterKind>())
}

/// The `--help` line of each formatter. The library's enums are
/// `#[non_exhaustive]`, so a table stands in for a `match`; a test checks
/// that every formatter has a line.
const FORMAT_HELP: &[(FormatterKind, &str)] = &[
    (
        FormatterKind::Json,
        "Compact JSON: an array of snippets per transcript",
    ),
    (
        FormatterKind::Pretty,
        "Indented JSON, easier to read (the default)",
    ),
    (
        FormatterKind::Text,
        "Plain text, one caption per line, no timestamps",
    ),
    (
        FormatterKind::TimestampedText,
        "Plain text with each caption's start time (MM:SS, or HH:MM:SS past an hour)",
    ),
    (FormatterKind::WebVtt, "WebVTT subtitles (.vtt)"),
    (FormatterKind::Srt, "SRT subtitles (.srt)"),
];

/// The `--help` line for a formatter.
fn format_help(kind: FormatterKind) -> &'static str {
    FORMAT_HELP
        .iter()
        .find(|(listed, _)| *listed == kind)
        .map_or("", |(_, help)| help)
}

/// `--raw`: YouTube's format names, each with its help.
fn raw_parser() -> impl TypedValueParser<Value = RawFormat> {
    PossibleValuesParser::new(
        RawFormat::ALL
            .iter()
            .map(|&format| PossibleValue::new(format.name()).help(raw_help(format))),
    )
    .try_map(|name| name.parse::<RawFormat>())
}

/// The `--help` line of each raw format; see [`FORMAT_HELP`].
const RAW_HELP: &[(RawFormat, &str)] = &[
    (
        RawFormat::Srv1,
        "XML, one element per caption with start and duration in seconds",
    ),
    (RawFormat::Srv2, "XML with times in milliseconds"),
    (
        RawFormat::Srv3,
        "XML with per-word timing for generated transcripts",
    ),
    (
        RawFormat::Json3,
        "JSON with per-word timing for generated transcripts",
    ),
    (RawFormat::Ttml, "TTML (Timed Text Markup Language)"),
    (RawFormat::Vtt, "WebVTT as YouTube writes it"),
];

/// The `--help` line for a raw format.
fn raw_help(format: RawFormat) -> &'static str {
    RAW_HELP
        .iter()
        .find(|(listed, _)| *listed == format)
        .map_or("", |(_, help)| help)
}

/// `--timeout`: seconds, possibly fractional.
fn parse_timeout(seconds: &str) -> Result<Duration, String> {
    seconds
        .parse::<f64>()
        .map_err(|e| e.to_string())
        .and_then(|s| Duration::try_from_secs_f64(s).map_err(|e| e.to_string()))
}

/// What a run produced.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Output {
    /// The formatted transcripts or transcript lists, for stdout.
    pub stdout: String,
    /// One message per video that failed, for stderr.
    pub errors: Vec<String>,
}

impl Output {
    /// Writes the errors to `stderr`, one per line, then the output to
    /// `stdout`.
    ///
    /// # Errors
    ///
    /// Any error from writing.
    pub fn write_to(&self, mut stdout: impl Write, mut stderr: impl Write) -> io::Result<()> {
        for error in &self.errors {
            writeln!(stderr, "{error}")?;
        }
        if !self.stdout.is_empty() {
            writeln!(stdout, "{}", self.stdout)?;
        }
        Ok(())
    }
}

impl Args {
    /// Backslashes removed, so an ID starting with `-` can go in escaped
    /// (`\-abc`).
    #[must_use]
    pub fn video_ids(&self) -> Vec<String> {
        self.video_ids
            .iter()
            .map(|id| id.replace('\\', ""))
            .collect()
    }

    /// Builds the client with the requested proxy. Webshare wins over the
    /// generic proxy.
    ///
    /// # Errors
    ///
    /// [`Error::InvalidProxyConfig`] if a proxy URL is invalid.
    pub fn build_api(&self) -> Result<YouTubeTranscriptApi, Error> {
        let mut builder = YouTubeTranscriptApi::builder();
        if let Some(timeout) = self.timeout {
            builder = builder.timeout(timeout);
        }
        if let (Some(username), Some(password)) =
            (&self.webshare_proxy_username, &self.webshare_proxy_password)
        {
            return builder
                .proxy_config(WebshareProxyConfig::new(username, password))
                .build();
        }
        if self.http_proxy.is_some() || self.https_proxy.is_some() {
            let proxy = GenericProxyConfig::new(self.http_proxy.clone(), self.https_proxy.clone())?;
            return builder.proxy_config(proxy).build();
        }
        builder.build()
    }

    /// The transcript to fetch: found by language, then translated.
    fn find(&self, list: &TranscriptList) -> Result<Transcript, Error> {
        let found = if self.matching.exclude_manually_created {
            list.find_generated_transcript(&self.languages)?
        } else if self.matching.exclude_generated {
            list.find_manually_created_transcript(&self.languages)?
        } else {
            list.find_transcript(&self.languages)?
        };
        self.translate
            .as_deref()
            .filter(|code| !code.is_empty())
            .map_or_else(|| Ok(found.clone()), |code| found.translate(code))
    }

    /// Fetches the transcript as parsed snippets or as raw text.
    async fn fetch(&self, list: &TranscriptList) -> Result<Fetched, Error> {
        let transcript = self.find(list)?;
        match self.raw {
            Some(format) => transcript.fetch_raw(format).await.map(Fetched::Raw),
            None => transcript
                .fetch(self.preserve_formatting)
                .await
                .map(Fetched::Parsed),
        }
    }
}

/// A transcript as the CLI fetched it.
enum Fetched {
    /// Parsed into snippets.
    Parsed(FetchedTranscript),
    /// In one of YouTube's own formats.
    Raw(String),
}

/// The error followed by its causes: `error: cause: cause`.
#[must_use]
pub fn report(error: &Error) -> String {
    let mut message = error.to_string();
    let mut source = std::error::Error::source(error);
    while let Some(cause) = source {
        message.push_str(": ");
        message.push_str(&cause.to_string());
        source = cause.source();
    }
    message
}

/// Runs the CLI against `api`.
pub async fn run(args: &Args, api: &YouTubeTranscriptApi) -> Output {
    let mut output = Output::default();
    if args.matching.exclude_manually_created && args.matching.exclude_generated {
        return output;
    }
    let mut lists = Vec::new();
    let mut transcripts = Vec::new();
    let mut raw = Vec::new();
    for video_id in args.video_ids() {
        let result = match api.list(&video_id).await {
            Ok(list) if args.list_transcripts => {
                lists.push(list.to_string());
                Ok(())
            }
            Ok(list) => {
                // The flag only turns matching on; `api` may have it on already.
                let matching = if args.matching.match_language_variants {
                    list.match_language_variants(true)
                } else {
                    list
                };
                args.fetch(&matching).await.map(|fetched| match fetched {
                    Fetched::Parsed(transcript) => transcripts.push(transcript),
                    Fetched::Raw(text) => raw.push(text),
                })
            }
            Err(error) => Err(error),
        };
        if let Err(error) = result {
            output.errors.push(report(&error));
        }
    }
    if args.list_transcripts {
        output.stdout = lists.join("\n\n");
    } else if args.raw.is_some() {
        output.stdout = raw.join("\n\n");
    } else if !transcripts.is_empty() {
        output.stdout = args.format.formatter().format_transcripts(&transcripts);
    }
    output
}
